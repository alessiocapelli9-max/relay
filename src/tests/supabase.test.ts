test('only the owner can delete a plan, and deletion removes membership and invalidates invites and stale saves',async()=>{
 const db=new PGlite();
 await db.exec("create role anon;create role authenticated;create schema auth;create function auth.uid() returns uuid language sql as $$ select nullif(current_setting('test.uid',true),'')::uuid $$;");
 await db.exec(readFileSync('supabase/migrations/202610240001_relay.sql','utf8'));
 await db.exec(readFileSync('supabase/migrations/202610260001_delete_plan.sql','utf8'));
 const call=async(user:string,p:unknown)=>{await db.query("select set_config('test.uid',$1,false)",[user]);const r=await db.query<{result:any}>('select public.relay_api($1::jsonb) as result',[JSON.stringify(p)]);return r.rows[0].result;};
 const remove=async(user:string,id:string)=>{await db.query("select set_config('test.uid',$1,false)",[user]);const r=await db.query<{result:any}>('select public.relay_delete_plan($1::uuid) as result',[id]);return r.rows[0].result;};
 const {id}=await call(alice,{action:'create',name:'Delete test',displayName:'Alice'});
 const {code}=await call(alice,{action:'invite',id});
 await call(bob,{action:'join',code,displayName:'Bob'});
 const original=await call(alice,{action:'get',id});
 assert.equal((await remove('',id)).status,401);
 assert.equal((await remove(bob,id)).status,403);
 assert.equal((await remove(carol,id)).status,403);
 assert.equal((await call(alice,{action:'get',id})).members.length,2);
 await db.exec('set role authenticated');
 assert.deepEqual(await remove(alice,id),{ok:true});
 assert.equal((await call(bob,{action:'get',id})).status,404);
 assert.equal((await call(alice,{action:'save',id,revision:1,state:original.state})).status,404);
 assert.equal((await call(carol,{action:'join',code,displayName:'Carol'})).status,404);
 assert.deepEqual((await call(alice,{action:'list'})).rooms,[]);
 assert.deepEqual((await call(bob,{action:'list'})).rooms,[]);
 await db.exec('reset role');
 const members=await db.query<{count:number}>('select count(*)::integer as count from relay.members where room_id=$1',[id]);
 assert.equal(members.rows[0].count,0);
 await db.exec('set role anon');
 await assert.rejects(()=>db.query('select public.relay_delete_plan($1::uuid)',[id]));
 await db.close();
});
